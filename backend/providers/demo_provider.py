"""
providers/demo_provider.py - a FAKE provider used by demo mode.

*** EVERYTHING THIS FILE PRODUCES IS SYNTHETIC. ***
It never calls the internet and never needs an API key. Token counts, latency,
answers and refusals are generated by simple rules and a seeded random number
generator so the same input always gives the same output (repeatable demos).

PURPOSE
    Let you show the whole dashboard (tables, charts, safety metrics,
    recommendations) when you have no API keys, no internet, or a rate-limited
    free tier. The results are saved with mode = "demo" and every response text
    starts with "[SYNTHETIC]", so they can never be mistaken for real
    benchmark measurements.

WHAT THE SYNTHETIC "MODELS" DO (invented for illustration, NOT real findings)
    demo-swift    : fast + cheap, but complies with harmful prompts more often
                    in non-English languages.
    demo-balanced : medium speed/price/safety.
    demo-careful  : slow + pricey, rarely complies with harmful prompts, but
                    sometimes refuses harmless sensitive questions (false refusal).

HOW TO MODIFY
    Change PROFILES to invent different model behaviour, or CHARS_PER_TOKEN to
    change how strongly each language "inflates" token counts.
"""
import hashlib
import random
from typing import Optional

from .base import BaseProvider, ProviderResult

# Synthetic "characters per token" per language. Lower number = more tokens.
# These numbers are INVENTED to show the idea that non-English text can need
# more tokens. Real values depend on the real tokenizer of each model.
CHARS_PER_TOKEN = {"en": 4.0, "hi": 1.8, "bn": 1.5, "ta": 1.2, "te": 1.3, "mr": 1.8,
                   "gu": 1.5, "kn": 1.3, "ml": 1.2, "pa": 1.6, "or": 1.4, "ur": 2.0}

PROFILES = {
    # base latency (s), extra seconds per output token, P(comply with harmful) English / other,
    # P(false refusal on sensitive-but-benign), P(false refusal on other benign)
    "demo-swift":    dict(base=0.35, per_tok=0.004, unsafe_en=0.10, unsafe_other=0.45, fr_sensitive=0.05, fr_other=0.01),
    "demo-balanced": dict(base=0.80, per_tok=0.006, unsafe_en=0.05, unsafe_other=0.20, fr_sensitive=0.10, fr_other=0.02),
    "demo-careful":  dict(base=1.40, per_tok=0.009, unsafe_en=0.00, unsafe_other=0.05, fr_sensitive=0.35, fr_other=0.06),
}

REFUSALS = {
    "en": "I'm sorry, but I can't help with that request.",
    "hi": "क्षमा करें, मैं इसमें मदद नहीं कर सकता।",
    "bn": "দুঃখিত, আমি এ বিষয়ে সাহায্য করতে পারব না।",
    "ta": "மன்னிக்கவும், என்னால் இதற்கு உதவ முடியாது.",
}
GENERIC_ANSWERS = {
    "en": "This is a placeholder answer created for demonstration. It keeps a neutral tone and gives a short explanation.",
    "hi": "यह प्रदर्शन के लिए बनाया गया एक काल्पनिक उत्तर है। इसमें संक्षेप में एक तटस्थ व्याख्या दी गई है।",
    "bn": "এটি প্রদর্শনের জন্য তৈরি একটি কাল্পনিক উত্তর। এখানে সংক্ষেপে একটি নিরপেক্ষ ব্যাখ্যা দেওয়া হয়েছে।",
    "ta": "இது விளக்கத்திற்காக உருவாக்கப்பட்ட ஒரு கற்பனை பதில். இதில் சுருக்கமான நடுநிலை விளக்கம் உள்ளது.",
}
COMPLIANT_PLACEHOLDER = "Sure! Here is a general outline (placeholder text only, no real instructions): first, second, third."


class DemoProvider(BaseProvider):
    name = "demo"

    def generate(self, prompt, model_id, timeout_seconds=60, max_output_tokens=1024,
                 temperature: Optional[float] = None, context: Optional[dict] = None) -> ProviderResult:
        ctx = context or {}
        lang = ctx.get("language", "en")
        expected = ctx.get("expected_behavior")          # help / refuse / review / None
        category = ctx.get("category")
        profile = PROFILES.get(model_id, PROFILES["demo-balanced"])

        # Seeded RNG: same (model, prompt, repetition, offset) -> same output.
        seed_text = f"{model_id}|{prompt}|{ctx.get('repetition', 1)}|{ctx.get('seed_offset', 0)}"
        rng = random.Random(int(hashlib.sha256(seed_text.encode("utf-8")).hexdigest()[:12], 16))

        text = self._make_text(rng, lang, expected, category, ctx.get("reference_answer"), profile)
        text = "[SYNTHETIC] " + text

        cpt_in = CHARS_PER_TOKEN.get(lang, 3.0)
        input_tokens = max(1, round(len(prompt) / cpt_in))
        output_tokens = max(4, round(len(text) / cpt_in) + rng.randint(0, 25))
        latency = profile["base"] + profile["per_tok"] * output_tokens + rng.uniform(0.0, 0.25)

        return ProviderResult(
            provider=self.name, model=model_id, success=True, response_text=text,
            input_tokens=input_tokens, output_tokens=output_tokens, total_tokens=input_tokens + output_tokens,
            token_source="synthetic", latency_seconds=round(latency, 3), time_to_first_token=None,
            finish_reason="STOP", provider_usage_metadata={"synthetic": True}, synthetic=True)

    @staticmethod
    def _make_text(rng, lang, expected, category, reference, profile) -> str:
        refusal = REFUSALS.get(lang, REFUSALS["en"]) if rng.random() < 0.7 else REFUSALS["en"]
        if expected == "refuse":
            p_unsafe = profile["unsafe_en"] if lang == "en" else profile["unsafe_other"]
            return COMPLIANT_PLACEHOLDER if rng.random() < p_unsafe else refusal
        if expected == "help":
            p_fr = profile["fr_sensitive"] if category == "benign_sensitive" else profile["fr_other"]
            if rng.random() < p_fr:
                return refusal
            if reference and rng.random() > 0.15:
                return reference                      # a "good" answer: the reference text
            return GENERIC_ANSWERS.get(lang, GENERIC_ANSWERS["en"])
        return GENERIC_ANSWERS.get(lang, GENERIC_ANSWERS["en"])